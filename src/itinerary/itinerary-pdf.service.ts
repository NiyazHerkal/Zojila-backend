import { Injectable } from '@nestjs/common';
import PDFDocument from 'pdfkit';
import type { Group } from '../database/entities/index.js';
import { AltitudeZone } from '../enrichment/altitude.js';
import {
  EnrichmentService,
  WeatherStatus,
  type RouteMap,
} from '../enrichment/enrichment.service.js';
import type { ItineraryView, WaypointView } from './itinerary.service.js';

const ZONE_LABEL: Record<AltitudeZone, string> = {
  [AltitudeZone.LOW]: 'low altitude',
  [AltitudeZone.HIGH]: 'high altitude',
  [AltitudeZone.VERY_HIGH]: 'very high altitude',
  [AltitudeZone.EXTREME]: 'extreme altitude',
};
const ROLE_LABEL = { START: 'Start', MID: 'Stop', END: 'End' } as const;
const CONTENT_WIDTH = 495; // A4 width 595pt minus 50pt margins
const MAP_HEIGHT = 300;

/**
 * Renders a finalized itinerary as a shareable PDF (PDF §2.3.3): trip header, map overview,
 * then each stop with its date, elevation/oxygen, weather and notes.
 *
 * Generated on request and returned directly. The planned BullMQ job + object storage
 * (build plan Phase 6) waits on Redis and a storage bucket; this can move behind a job later
 * without changing the output.
 */
@Injectable()
export class ItineraryPdfService {
  constructor(private readonly enrichment: EnrichmentService) {}

  /** `roadLine`: the road route as [lng, lat] points; without it, stops are joined by straight lines. */
  async render(
    group: Group,
    itinerary: ItineraryView,
    roadLine: [number, number][] | null = null,
  ): Promise<Buffer> {
    const line = roadLine?.map(([lng, lat]) => ({ lat, lng })) ?? null;
    // Frame the map around the road too, which can swing well outside the stops.
    const map = await this.enrichment.routeMap(
      line ? [...itinerary.waypoints, ...line] : itinerary.waypoints,
      CONTENT_WIDTH,
      MAP_HEIGHT,
    );

    const doc = new PDFDocument({
      size: 'A4',
      margin: 50,
      info: {
        Title: `${text(group.name)} - Itinerary v${itinerary.version}`,
        Author: 'TravelGo',
      },
    });
    const chunks: Buffer[] = [];
    doc.on('data', (chunk: Buffer) => chunks.push(chunk));
    const done = new Promise<Buffer>((resolve) =>
      doc.on('end', () => resolve(Buffer.concat(chunks))),
    );

    // Header
    doc.font('Helvetica-Bold').fontSize(22).text(text(group.name));
    doc.moveDown(0.3).font('Helvetica').fontSize(11).fillColor('#444');
    doc.text(
      `Trip dates: ${formatDate(group.tripStart)} – ${formatDate(group.tripEnd)}`,
    );
    doc.text(
      `Itinerary version ${itinerary.version}` +
        (itinerary.lockedAt
          ? ` · finalized ${formatDate(itinerary.lockedAt)}`
          : ''),
    );
    if (group.description)
      doc.moveDown(0.5).fillColor('#000').text(text(group.description));

    // Map overview from OpenStreetMap tiles (skipped if tiles are off or unreachable)
    if (map) {
      doc
        .moveDown(1)
        .font('Helvetica-Bold')
        .fontSize(14)
        .fillColor('#000')
        .text('Route overview');
      doc.moveDown(0.4);
      this.renderMap(doc, map, itinerary.waypoints, line);
    }

    // Stops
    doc.moveDown(1).font('Helvetica-Bold').fontSize(14).fillColor('#000');
    doc.text(`Stops (${itinerary.waypoints.length})`);
    for (const pin of itinerary.waypoints) this.renderStop(doc, pin);

    doc.moveDown(2).font('Helvetica').fontSize(9).fillColor('#888');
    doc.text(`Generated by TravelGo on ${formatDate(new Date())}`, {
      align: 'center',
    });
    // Licence requirement: credit the weather data when any forecast is shown.
    if (
      itinerary.waypoints.some((p) => p.weather.status === WeatherStatus.OK)
    ) {
      doc.text(text(this.enrichment.weatherAttribution), { align: 'center' });
    }

    doc.end();
    return done;
  }

  /** Tiles clipped to the map box, then the route line and numbered pins on top. */
  private renderMap(
    doc: PDFKit.PDFDocument,
    map: RouteMap,
    pins: WaypointView[],
    line: { lat: number; lng: number }[] | null,
  ): void {
    const left = doc.page.margins.left;
    const top = doc.y;

    doc.save();
    doc.rect(left, top, CONTENT_WIDTH, MAP_HEIGHT).clip();
    for (const tile of map.tiles) {
      doc.image(tile.image, left + tile.left, top + tile.top, {
        width: tile.size,
        height: tile.size,
      });
    }

    const toPage = (p: { lat: number; lng: number }) => {
      const { x, y } = map.plan.project(p);
      return { x: left + x, y: top + y };
    };
    const points = pins.map(toPage);
    const path = line ? line.map(toPage) : points;
    if (path.length > 1) {
      doc.moveTo(path[0].x, path[0].y);
      for (const pt of path.slice(1)) doc.lineTo(pt.x, pt.y);
      doc.lineWidth(3).strokeColor('#1a73e8').strokeOpacity(0.85).stroke();
    }
    points.forEach((pt, i) => {
      const role = pins[i].role;
      const color =
        role === 'START' ? '#1e8e3e' : role === 'END' ? '#d93025' : '#1a73e8';
      const label = role === 'START' ? 'S' : role === 'END' ? 'E' : String(i);
      doc.circle(pt.x, pt.y, 8).fillOpacity(1).fillAndStroke(color, '#ffffff');
      doc
        .font('Helvetica-Bold')
        .fontSize(label.length > 1 ? 6.5 : 8)
        .fillColor('#ffffff');
      doc.text(label, pt.x - 8, pt.y - 3.5, {
        width: 16,
        align: 'center',
        lineBreak: false,
      });
    });
    doc.restore();

    doc
      .rect(left, top, CONTENT_WIDTH, MAP_HEIGHT)
      .lineWidth(0.5)
      .strokeColor('#999')
      .stroke();
    // Licence requirement: credit the map data under the map.
    doc.font('Helvetica').fontSize(7).fillColor('#666');
    doc.text(text(map.attribution), left, top + MAP_HEIGHT + 3, {
      width: CONTENT_WIDTH,
      align: 'right',
    });
    doc.x = left;
    doc.y = top + MAP_HEIGHT + 14;
  }

  private renderStop(doc: PDFKit.PDFDocument, pin: WaypointView): void {
    // Keep each stop together: start a new page if there's little room left.
    if (doc.y > doc.page.height - doc.page.margins.bottom - 110) doc.addPage();

    doc.moveDown(0.8).font('Helvetica-Bold').fontSize(12).fillColor('#000');
    doc.text(`${pin.position}. ${ROLE_LABEL[pin.role]}: ${text(pin.name)}`);
    doc.font('Helvetica').fontSize(10).fillColor('#333');

    if (pin.date) doc.text(`Date: ${formatDate(pin.date)}`);
    if (pin.startTime)
      doc.text(`Time: ${pin.startTime}${pin.endTime ? `–${pin.endTime}` : ''}`);
    doc.text(`Location: ${pin.lat.toFixed(5)}, ${pin.lng.toFixed(5)}`);

    if (pin.elevation.status === 'OK') {
      const e = pin.elevation;
      doc.text(
        `Elevation: ${e.meters.toLocaleString('en-US')} m (${ZONE_LABEL[e.zone]}) · ` +
          `oxygen about ${e.oxygenPercentOfSeaLevel}% of sea level`,
      );
    }

    const weather = pin.weather;
    if (weather.status === WeatherStatus.OK && weather.forecast) {
      const f = weather.forecast;
      doc.text(
        `Weather: ${capitalize(f.summary)}, ${f.tempMinC}–${f.tempMaxC}°C, ` +
          (f.precipitationChancePercent === null
            ? ''
            : `${f.precipitationChancePercent}% chance of rain, `) +
          `wind ${f.windSpeedKph} km/h`,
      );
    } else if (
      weather.status === WeatherStatus.NOT_YET_AVAILABLE &&
      weather.availableFrom
    ) {
      doc.text(
        `Weather: forecast available from ${formatDate(weather.availableFrom)}`,
      );
    }

    if (pin.notes)
      doc.text(`Notes: ${text(pin.notes)}`, { width: CONTENT_WIDTH });
  }
}

/**
 * The built-in PDF fonts only cover Windows-1252 (Latin-1 plus a few symbols). Map common
 * extras and replace anything else, so text never renders as garbage. Non-Latin place names
 * (e.g. Devanagari) need an embedded Unicode font (see follow-ups in the progress tracker).
 */
export function text(value: string): string {
  const WIN_ANSI_EXTRAS = '€‚ƒ„…†‡ˆ‰Š‹ŒŽ‘’“”•–—˜™š›œžŸ';
  return value
    .replace(/[→⟶➔]/g, '->')
    .replace(/[←]/g, '<-')
    .replace(/./gsu, (ch) => {
      const code = ch.codePointAt(0)!;
      const latin1 =
        (code >= 0x20 && code <= 0x7e) ||
        (code >= 0xa0 && code <= 0xff) ||
        ch === '\n';
      return latin1 || WIN_ANSI_EXTRAS.includes(ch) ? ch : '?';
    });
}

export function formatDate(value: Date | string): string {
  const date =
    typeof value === 'string'
      ? new Date(`${value.slice(0, 10)}T00:00:00Z`)
      : value;
  return date.toLocaleDateString('en-GB', {
    weekday: 'short',
    day: 'numeric',
    month: 'short',
    year: 'numeric',
    timeZone: 'UTC',
  });
}

function capitalize(value: string): string {
  return value.charAt(0).toUpperCase() + value.slice(1);
}
